export type GlyphName = keyof typeof glyphs;

export function PixelIcon({ name, size = 16, color = "currentColor", className = "" }: {
  name: GlyphName;
  size?: number;
  color?: string;
  className?: string;
}) {
  const rows = glyphs[name];
  return (
    <svg viewBox="0 0 8 8" width={size} height={size} className={`crisp ${className}`} aria-hidden="true">
      {rows.flatMap((row, y) =>
        [...row].map((cell, x) => (cell === "#" ? <rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} fill={color} /> : null)),
      )}
    </svg>
  );
}
